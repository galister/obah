use serde::{Deserialize, Deserializer, Serialize, Serializer};
use serde_json::Value;
use std::collections::BTreeMap;
use std::fmt;

pub type ExtraFields = BTreeMap<String, Value>;
pub type BindingParameters = BTreeMap<String, Value>;

/// a string-valued enum that preserves unknown values
macro_rules! string_enum {
    (
        $(#[$enum_meta:meta])*
        pub enum $name:ident {
            $(
                $variant:ident => $value:literal
            ),* $(,)?
        }
    ) => {
        $(#[$enum_meta])*
        #[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
        pub enum $name {
            $(
                $variant,
            )*
            Other(String),
        }

        impl $name {
            pub fn as_str(&self) -> &str {
                match self {
                    $(
                        Self::$variant => $value,
                    )*
                    Self::Other(value) => value,
                }
            }
        }

        impl AsRef<str> for $name {
            fn as_ref(&self) -> &str {
                self.as_str()
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str(self.as_str())
            }
        }

        impl Serialize for $name {
            fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
            where
                S: Serializer,
            {
                serializer.serialize_str(self.as_str())
            }
        }

        impl<'de> Deserialize<'de> for $name {
            fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
            where
                D: Deserializer<'de>,
            {
                let value = String::deserialize(deserializer)?;

                Ok(match value.as_str() {
                    $(
                        $value => Self::$variant,
                    )*
                    _ => Self::Other(value),
                })
            }
        }
    };
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ActionManifest {
    #[serde(default)]
    pub actions: Vec<ActionDefinition>,

    #[serde(default)]
    pub action_sets: Vec<ActionSetDefinition>,

    #[serde(default)]
    pub default_bindings: Vec<DefaultBinding>,

    #[serde(default)]
    pub localization: Vec<Localization>,

    #[serde(flatten)]
    pub extra: ExtraFields,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ActionDefinition {
    /// E.g. `/actions/main/in/jump`.
    pub name: String,

    #[serde(rename = "type")]
    pub kind: ActionType,

    #[serde(default)]
    pub requirement: Option<ActionRequirement>,

    /// present for skeleton actions
    ///
    /// `/skeleton/hand/left`
    /// `/skeleton/hand/right`
    #[serde(default)]
    pub skeleton: Option<String>,

    #[serde(flatten)]
    pub extra: ExtraFields,
}

string_enum! {
    pub enum ActionType {
        Boolean => "boolean",
        Vector1 => "vector1",
        Vector2 => "vector2",
        Vector3 => "vector3",
        Pose => "pose",
        Skeleton => "skeleton",
        Vibration => "vibration",
    }
}

string_enum! {
    pub enum ActionRequirement {
        Mandatory => "mandatory",
        Suggested => "suggested",
        Optional => "optional",
    }
}

